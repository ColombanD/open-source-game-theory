"""Generate `latex/figures and tables/moran_body.tex`: Moran stationary shares of the paper's nine-bot
zoo (`body-dimcid`) at t = 1, PA-S', hinge cells at the ENGINE side (the floor value).

Run from `app/`:  uv run python ../latex/scripts/gen_moran_body.py [engine_side|hinge_side]
Reads the run directory's moran/stationary.json and ess/payoff_matrix_numeric.csv. Do not edit the output by hand.
"""
from __future__ import annotations
import csv, json, sys
from pathlib import Path

POLICY = sys.argv[1] if len(sys.argv) > 1 else "engine_side"
APP = Path(__file__).resolve().parents[2] / "app"
RUNS = APP / "generated" / "egt" / "runs"
ZOO = "body8"  # the paper's body since 2026-10-13: eight bots, no CupodTrollBot
prefix = f"{ZOO}_sprime_" + ("" if POLICY == "engine_side" else f"{POLICY}_")
(run_dir,) = sorted(RUNS.glob(prefix + "t100_a030_*"))
OUT = Path(__file__).resolve().parents[1] / "figures and tables" / ("moran_body.tex" if POLICY == "engine_side" else f"moran_body_{POLICY}.tex")

COLS = ["DupocBot", "TitForTatBot", "DefectBot", "CooperateBot"]
mo = json.load(open(run_dir / "moran" / "stationary.json"))
bots = mo["names"]; n = len(bots); thr = 1.5 / n
others = [b for b in bots if b not in COLS]
rows = list(csv.reader(open(run_dir / "ess" / "payoff_matrix_numeric.csv"))); hdr = rows[0][1:]
diag = {r[0]: float(r[1 + hdr.index(r[0])]) > 0 for r in rows[1:]}

def fmt(x, star): return f"{100*x:.1f}" + ("$^{\\star}$" if star else "")
lines, n_alone, realized_100_1, max_other = [], 0, None, 0.0
for i, p in enumerate(mo["points"]):
    x = dict(p["stationary"]); ss = set(p["stochastically_stable"])
    if ss == {"DupocBot"}: n_alone += 1
    if p["population"] == 100 and p["beta"] == 1.0:
        realized_100_1 = sum(s * diag[b] for b, s in x.items())
    max_other = max(max_other, *(x.get(b, 0) for b in others))
    beta = p["beta"]; beta_s = "1" if beta == 1 else f"{beta:g}"
    selfcoop = sum(v * diag[b] for b, v in x.items())
    cells = ([fmt(x.get(b, 0), b in ss) for b in COLS] + [fmt(sum(x.get(b, 0) for b in others), False)]
             + [f"{selfcoop:.2f}"])
    sep = "\\\\\\midrule" if (i + 1) % 3 == 0 and i + 1 < len(mo["points"]) else "\\\\"
    lines.append(f"{p['population']} & {beta_s} & " + " & ".join(cells) + f" {sep}")
lines[-1] = lines[-1][:-2] + "\\\\\\bottomrule"
side = "engine side (the floor value)" if POLICY == "engine_side" else "hinge side"
tex = [
    f"% figures and tables/{OUT.name} — Moran stationary shares, eight-bot zoo (body8), t = 1, PA-S', hinge cells at the {side}.",
    f"% GENERATED by latex/scripts/gen_moran_body.py from {run_dir.relative_to(APP.parent)}/moran/stationary.json. Do not edit by hand.",
    f"% Shares in %, rounded from the six-decimal values. \"others\" = {' + '.join(others)} (each <= {max_other:.3f} at every point).",
    "\\begin{table}[t]\\centering\\small",
    "\\begin{tabular}{@{}llrrrrrr@{}}\\toprule",
    "$M$ & $\\beta$ & " + " & ".join(f"\\texttt{{{b}}}" for b in COLS) + " & others & self-coop \\\\\\midrule",
    *lines,
    "\\end{tabular}",
    f"\\caption{{Moran stationary distribution on the eight-bot zoo at full transparency, hinge cells at the {side}: population shares in \\% (small-mutation limit) for population size $M$ and selection intensity $\\beta$. "
    f"$^{{\\star}}$ marks the stochastically stable set at that point (stationary mass $\\ge 1.5/N = {thr:.3f}$); \\texttt{{DupocBot}} is the unique stable type at {n_alone} of the 9 points. "
    f"Shares are population shares, not cooperation rates: the last column is the fraction of the long run spent in self-cooperating states, i.e.\\ the stationary mass of the types whose self-play cell is $(C,C)$ ({', '.join(f'\\texttt{{{b}}}' for b in COLS + others if diag[b])}); at $(M,\\beta)=(100,1)$ it is ${realized_100_1:.3f}$. "
    f"``others'' = {', '.join(f'\\texttt{{{b}}}' for b in others)}, each at most ${max_other:.3f}$ everywhere and never stochastically stable.}}",
    "\\label{tab:moran-body}" if POLICY == "engine_side" else f"\\label{{tab:moran-body-{POLICY.replace('_', '-')}}}",
    "\\end{table}",
]
OUT.write_text("\n".join(tex) + "\n", encoding="utf-8")
print(f"wrote {OUT} from {run_dir.name}: N={n}, threshold {thr:.3f}, Dup alone at {n_alone}/9, realized {realized_100_1:.3f}, max other {max_other:.3f}")
