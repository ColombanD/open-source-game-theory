"""Generate `latex/figures and tables/zoo_ladder.tex`: the ladder of nested zoos at t = 1, PA-S', hinge cells
at the engine side, one row per zoo with the Nash and Moran headlines (the ESS count is stated in the caption).

Run from `app/`:  uv run python ../latex/scripts/gen_zoo_ladder.py [engine_side|hinge_side]
Reads each zoo's t = 1 run directory at the first positive caution of the grid (the base matrix). Do not edit the output by hand.
"""
from __future__ import annotations
import csv, json, sys
from pathlib import Path

POLICY = sys.argv[1] if len(sys.argv) > 1 else "engine_side"
APP = Path(__file__).resolve().parents[2] / "app"
RUNS = APP / "generated" / "egt" / "runs"
OUT = Path(__file__).resolve().parents[1] / "figures and tables" / (
    "zoo_ladder.tex" if POLICY == "engine_side" else f"zoo_ladder_{POLICY}.tex")
LADDER = [  # (registry key, label)
    ("nonprovers+dupoc", "non-provers + \\texttt{DupocBot}"),
    ("body8", "\\texttt{body}"),
    ("body8+trolls", "\\texttt{body} + trolls"),
    ("body8+trolls+provers", "\\texttt{body} + trolls + \\texttt{CIMCIC} + \\texttt{DIMDID}"),
]
ABBREV = {"CooperateBot": "Coop", "DefectBot": "Def", "TitForTatBot": "TFT", "DupocBot": "Dup", "CupodBot": "Cup",
          "CupodTrollBot": "CupT", "DupocTrollBot": "DupT", "DBot": "DB", "EBot": "EB", "OBot": "OB", "CIMCIC": "CIM",
          "DIMDID": "DIMDID"}
tt = lambda b: f"\\texttt{{{ABBREV.get(b, b)}}}"
setof = lambda bots: "\\{" + ", ".join(tt(b) for b in bots) + "\\}"

rows, notes = [], []
for key, label in LADDER:
    (d,) = sorted(RUNS.glob(f"{key}_sprime_" + ("" if POLICY == "engine_side" else f"{POLICY}_") + "t100_a0[1-9]*"))  # the base matrix: t = 1, any α > 0 (α = 0 is the all-cooperate matrix)
    s = json.load(open(d / "summary.json")); n = s["n_types"]
    ess = [r["type"] for r in csv.DictReader(open(d / "ess/ess_summary.csv")) if r["is_ESS"] == "True"]
    eq = [json.loads(l) for l in open(d / "nash/latest/equilibria.jsonl")]
    comps: dict[int, dict] = {}
    for e in eq:
        c = comps.setdefault(e["component_id"], {"sup": set(), "coop": 0.0})
        c["sup"] |= set(e["support_row_names"]) | set(e["support_col_names"])
        c["coop"] = max(c["coop"], e["cooperation_rate_float"])
    full = [c for c in comps.values() if c["coop"] >= 0.999]
    assert len(full) == 1, (key, [sorted(c["sup"]) for c in comps.values()])
    mo = json.load(open(d / "moran/stationary.json"))
    (pt,) = [p for p in mo["points"] if p["population"] == 100 and p["beta"] == 1.0]
    x = dict(pt["stationary"]); ss = sorted(pt["stochastically_stable"])
    share = sum(x[b_] for b_ in ss)
    n_alone = sum(1 for p in mo["points"] if sorted(p["stochastically_stable"]) == ss)
    assert not ess, (key, ess)  # the caption states "no pure ESS on any row"
    rows.append(
        f"{label} & {len(comps)} ({len(eq)}) & {setof(sorted(full[0]['sup']))} & "
        f"{setof(ss)} {100*share:.1f}\\% \\\\")
    notes.append((label, ss, [(b_, 100*x[b_]) for b_ in ss], n_alone))
rows[-1] = rows[-1][:-2] + "\\\\\\bottomrule"
side = "engine side (the floor value)" if POLICY == "engine_side" else "hinge side"
split = "; ".join(f"on the row {lab} the share splits as " + ", ".join(f"{tt(b_)} {v:.1f}\\%" for b_, v in sh)
                  for lab, ss, sh, _ in notes if len(ss) > 1)
alone = sorted({a for _, _, _, a in notes})
tex = [
    f"% figures and tables/{OUT.name} — the ladder of nested zoos at t = 1, PA-S', hinge cells at the {side}: the Nash and Moran headlines per zoo.",
    "% GENERATED by latex/scripts/gen_zoo_ladder.py from app/generated/egt/runs/<zoo>_sprime[_hinge_side]_t100_a0*_*/ (the base matrix). Do not edit by hand.",
    "\\begin{table}[t]\\centering\\small",
    "\\setlength{\\tabcolsep}{3pt}",
    "\\begin{tabular}{@{}lcll@{}}\\toprule",
    " & \\multicolumn{2}{c}{Nash} & Moran $(100,1)$ \\\\",
    "\\cmidrule(lr){2-3}",
    "zoo & comps (extreme NE) & cooperative component & selected set, share \\\\\\midrule",
    *rows,
    "\\end{tabular}",
    f"\\caption{{The ladder of nested zoos at full transparency, hinge cells at the {side}, with the Nash and Moran headlines. No pure ESS exists on any row. "
    "Nash: the number of connected components of extreme equilibria (and of extreme equilibria), and the support of the fully cooperative component. "
    "Moran: the stochastically stable set at $(M,\\beta) = (100,1)$ with its stationary mass"
    + (f"; {split}" if split else "") + "; on every row that set is the selected set at "
    + (f"{alone[0]} of the nine $(M,\\beta)$ points" if len(alone) == 1 else "/".join(map(str, alone)) + " of the nine $(M,\\beta)$ points") + ".}",
    "\\label{tab:zoo-ladder}" if POLICY == "engine_side" else f"\\label{{tab:zoo-ladder-{POLICY.replace('_', '-')}}}",
    "\\end{table}",
]
OUT.write_text("\n".join(tex) + "\n", encoding="utf-8")
print(f"wrote {OUT}: {len(rows)} rows; sole-selected counts {alone}")
