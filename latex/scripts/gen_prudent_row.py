"""Generate `latex/figures and tables/prudent_row.tex`: PrudentBot's outcome against every bot the paper
mentions, PA-S' (the export `app/generated/sprime_outcome_theorems.json`), hinge cells shown with both branches.

Run from `app/`:  uv run python ../latex/scripts/gen_prudent_row.py
Do not edit the output by hand.
"""
from __future__ import annotations
import json
from pathlib import Path
from pd_runner.eval.sprime_floors import HINGE_SIDE_PAIRS

APP = Path(__file__).resolve().parents[2] / "app"
OUT = Path(__file__).resolve().parents[1] / "figures and tables" / "prudent_row.tex"
BOTS = [  # body8, then the ladder rungs, then the appendix bots, then itself
    "CooperateBot", "CupodBot", "DBot", "DefectBot", "DupocBot", "EBot", "OBot", "TitForTatBot",
    "CupodTrollBot", "DupocTrollBot", "CIMCIC", "DIMDID", "DIMCID", "PrudentBot"]
d = json.load(open(APP / "generated" / "sprime_outcome_theorems.json"))
th, fl = d["theorems"], d["floors"]


def lookup(x: str):
    """(kind, (PrudentBot's action, x's action), regime, hinge-side pair or None), from either orientation."""
    for t in th:
        if (t["left_bot"], t["right_bot"]) == ("PrudentBot", x):
            return "cell", tuple(t["pair"]), t["budget_regime"], None
        if (t["left_bot"], t["right_bot"]) == (x, "PrudentBot"):
            return "cell", (t["pair"][1], t["pair"][0]), t["budget_regime"], None
    for f in fl:
        h = HINGE_SIDE_PAIRS.get(f["dichotomy"])
        if (f["left_bot"], f["right_bot"]) == ("PrudentBot", x):
            return "floor", tuple(f["pair"]), f["budget_regime"], tuple(h)
        if (f["left_bot"], f["right_bot"]) == (x, "PrudentBot"):
            return "floor", (f["pair"][1], f["pair"][0]), f["budget_regime"], (h[1], h[0])
    raise SystemExit(f"no S' cell for PrudentBot vs {x}")


def pair(p: tuple[str, str], sup: str = "") -> str:
    """The outcome matrix's cell style: `CC`/`DD` shaded, `CD`/`DC` plain, an optional dagger."""
    fill = {("C", "C"): "\\cellcolor{green!18}", ("D", "D"): "\\cellcolor{black!12}"}.get(p, "")
    return f"{fill}{p[0]}{p[1]}" + (f"$^{{{sup}}}$" if sup else "")


ABBR = {"CooperateBot": "Coop", "CupodBot": "Cup", "DBot": "DB", "DefectBot": "Def", "DupocBot": "Dup", "EBot": "EB",
        "OBot": "OB", "TitForTatBot": "TFT", "CupodTrollBot": "CupT", "DupocTrollBot": "DupT", "CIMCIC": "CIM",
        "DIMDID": "DID", "DIMCID": "DIMCID", "PrudentBot": "Prud"}
floor_row, hinge_row, heads = [], [], []
for x in BOTS:
    kind, p, regime, h = lookup(x)
    heads.append(f"\\texttt{{{ABBR[x]}}}")
    if kind == "cell":
        floor_row.append(pair(p)); hinge_row.append("")  # a theorem holds on both sides: nothing to show
    else:
        floor_row.append(pair(p, "\\ddagger")); hinge_row.append(pair(h))
tex = [
    "% figures and tables/prudent_row.tex — PrudentBot against every bot the paper mentions, PA-S', both branches of each hinge cell.",
    "% GENERATED by latex/scripts/gen_prudent_row.py from app/generated/sprime_outcome_theorems.json — do not edit by hand.",
    "% Requires: booktabs, xcolor with colortbl (\\cellcolor).",
    "\\begin{table}[t]\\centering\\small",
    "\\setlength{\\tabcolsep}{3pt}",
    "\\caption{\\texttt{PrudentBot}$(k)$ against every program of the paper in $S'$, for all large $k$, written as its action followed by the opponent's. A hinge cell ($\\ddagger$) is a floor dichotomy: the first row gives the floor side ($\\neg H_k$, the one the matrices of \\cref{section:Results-Base} use), the second the hinge side ($H_k$); the other cells are theorems, hold on both sides, and leave the second row empty. Green: mutual cooperation; gray: mutual defection.}",
    "\\label{tab:prudent-row}",
    "\\begin{tabular}{@{}l" + "c" * len(BOTS) + "@{}}\\toprule",
    " & " + " & ".join(heads) + " \\\\\\midrule",
    "floor side & " + " & ".join(floor_row) + " \\\\",
    "hinge side & " + " & ".join(hinge_row) + " \\\\\\bottomrule",
    "\\end{tabular}",
    "\\end{table}",
]
OUT.write_text("\n".join(tex) + "\n", encoding="utf-8")
print(f"wrote {OUT}: {len(BOTS)} columns")
