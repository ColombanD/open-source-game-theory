"""Generate `latex/figures and tables/replicator_body.tex`: the replicator basins of attraction of the paper's
eight-bot zoo (`body8`) at t = 1, PA-S', hinge cells at the ENGINE side (the floor value).

Run from `app/`:  uv run python ../latex/scripts/gen_replicator_body.py [engine_side|hinge_side]
Reads the run directory's replicator/basins.json (201 interior starts, endpoints grouped by SUPPORT: the rest
points form continua, so a group's "composition" is the mean endpoint and "spread" the largest coordinate
distance within the group). Do not edit the output by hand.
"""
from __future__ import annotations
import json, sys
from pathlib import Path

POLICY = sys.argv[1] if len(sys.argv) > 1 else "engine_side"
ZOO = "body8"
APP = Path(__file__).resolve().parents[2] / "app"
prefix = f"{ZOO}_sprime_" + ("" if POLICY == "engine_side" else f"{POLICY}_")
(run_dir,) = sorted((APP / "generated" / "egt" / "runs").glob(prefix + "t100_a0[1-9]*"))
OUT = Path(__file__).resolve().parents[1] / "figures and tables" / (
    "replicator_body.tex" if POLICY == "engine_side" else f"replicator_body_{POLICY}.tex")
ABBREV = {"CooperateBot": "Coop", "DefectBot": "Def", "TitForTatBot": "TFT", "DupocBot": "Dup", "CupodBot": "Cup",
          "CupodTrollBot": "CupT", "DupocTrollBot": "DupT", "DBot": "DB", "EBot": "EB", "OBot": "OB"}
tt = lambda b: f"\\texttt{{{ABBREV.get(b, b)}}}"

b = json.load(open(run_dir / "replicator" / "basins.json"))
reached = [a for a in b["attractors"] if a["n_interior"] > 0]
n = b["n_interior_samples"]
rows = []
for a in sorted(reached, key=lambda a: -a["n_interior"]):
    comp = ", ".join(f"{tt(name)} {100*s:.0f}\\%" for name, s in a["shares"])
    rows.append(f"\\{{{', '.join(tt(x) for x in a['support'])}\\}} & {comp} & {100*a['basin_fraction']:.1f}\\% ({a['n_interior']}) & {a['spread']:.2f} \\\\")
rows[-1] = rows[-1][:-2] + "\\\\\\bottomrule"
all_dup = all("DupocBot" in a["support"] for a in reached)
side = "engine side (the floor value)" if POLICY == "engine_side" else "hinge side"
tex = [
    f"% figures and tables/{OUT.name} — replicator basins, eight-bot zoo (body8), t = 1, PA-S', hinge cells at the {side}.",
    f"% GENERATED by latex/scripts/gen_replicator_body.py from {run_dir.relative_to(APP.parent)}/replicator/basins.json. Do not edit by hand.",
    "\\begin{table}[t]\\centering\\small",
    "\\begin{tabular}{@{}llrc@{}}\\toprule",
    f"attractor (support) & mean endpoint & basin (of {n} starts) & spread \\\\\\midrule",
    *rows,
    "\\end{tabular}",
    f"\\caption{{Replicator dynamics on the eight-bot zoo at full transparency, hinge cells at the {side}: where {n} interior starting points end up, grouped by the support of the endpoint. "
    f"The endpoints on a support form a continuum of neutrally stable rest points rather than a single point, so a group is described by its mean endpoint and by its spread, the largest coordinate distance between two of its endpoints; "
    f"the basin is the fraction of starts that reach the group. All {n} starts converge"
    + ("; every one of them ends on a support containing \\texttt{Dup}. " if all_dup else ". ")
    + "The eight monoculture starts, one per vertex, are measure-zero and not counted.}",
    "\\label{tab:replicator-body}" if POLICY == "engine_side" else f"\\label{{tab:replicator-body-{POLICY.replace('_', '-')}}}",
    "\\end{table}",
]
OUT.write_text("\n".join(tex) + "\n", encoding="utf-8")
print(f"wrote {OUT} from {run_dir.name}: {len(reached)} attractors reached, unconverged {b['n_unconverged']}")
