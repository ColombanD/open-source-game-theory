"""Generate `latex/figures and tables/outcome_matrix_base.tex`: the body zoo's S' outcome
matrix at a shared budget, hinge cells (floor dichotomies) in their own colour.

Run from `app/`:  uv run python ../latex/scripts/gen_outcome_matrix_body.py
Reads the S' export through `pd_runner` under BOTH floor policies, so each hinge cell's
other branch is known and listed in the caption. Do not edit the output by hand.
"""
from __future__ import annotations
import json, warnings
from pathlib import Path
warnings.simplefilter("ignore")
from pd_runner.tau.matrix import load_tau_matrix
from pd_runner.eval import outcome_matrix as om

ORDER = ["CooperateBot", "DefectBot", "TitForTatBot", "DBot", "OBot", "EBot",
         "DupocBot", "CupodBot"]
OUT = Path(__file__).resolve().parents[1] / "figures and tables" / "outcome_matrix_base.tex"

eng = load_tau_matrix(tuple(ORDER), source="sprime", floor_policy="engine_side")
hin = load_tau_matrix(tuple(ORDER), source="sprime", floor_policy="hinge_side")
digest = json.loads(om._EXPORT_FILES["sprime"].read_text())["source_digest"]

def pair(m, r, c):
    cell = m.cell(r, c); return cell.row_action + cell.col_action

unexploitable = [b for b in ORDER if all(pair(eng, b, c) != "CD" for c in ORDER)]
unexploitable_h = [b for b in ORDER if all(pair(hin, b, c) != "CD" for c in ORDER)]

def name(b):
    t = f"\\texttt{{{b}}}"
    return f"\\colorbox{{hlfill}}{{{t}}}" if b in unexploitable else t

def render(r, c):
    p = pair(eng, r, c)
    if eng.cell(r, c).is_floor:
        return f"\\hg{{{p}}}"
    return {"CC": "\\cc", "DD": "\\dd", "CD": "\\cd", "DC": "\\dc"}[p]

hinge_pairs = sorted({tuple(sorted((r, c))) for r in ORDER for c in ORDER if eng.cell(r, c).is_floor})
hinge_list = "; ".join(
    f"\\texttt{{{a}}}--\\texttt{{{b}}} {pair(eng, a, b)} $\\to$ {pair(hin, a, b)}" for a, b in hinge_pairs)

lines = [
    f"% figures and tables/outcome_matrix_base.tex — GENERATED by latex/scripts/gen_outcome_matrix_body.py from",
    f"% app/generated/sprime_outcome_theorems.json (source_digest {digest}). Do not edit by hand.",
    "% Requires: booktabs, graphicx (rotatebox), xcolor with colortbl (\\cellcolor).",
    "\\begin{table}[t]\\centering\\scriptsize",
    "\\colorlet{ccfill}{green!18}\\colorlet{ddfill}{black!12}\\colorlet{hlfill}{yellow!35}\\colorlet{hgfill}{orange!40}",
    "\\newcommand{\\cc}{\\cellcolor{ccfill}CC}\\newcommand{\\dd}{\\cellcolor{ddfill}DD}",
    "\\newcommand{\\cd}{CD}\\newcommand{\\dc}{DC}\\newcommand{\\hg}[1]{\\cellcolor{hgfill}#1$^{\\ddagger}$}",
    "\\setlength{\\tabcolsep}{3pt}",
    "\\begin{tabular}{@{}l" + "c" * len(ORDER) + "@{}}\\toprule",
    " & " + " & ".join(f"\\rotatebox{{90}}{{{name(b)}}}" for b in ORDER) + " \\\\\\midrule",
]
for r in ORDER:
    lines.append(name(r) + " & " + " & ".join(render(r, c) for c in ORDER) + " \\\\")
lines[-1] += "\\bottomrule"
lines += [
    "\\end{tabular}",
    "\\caption{Outcome matrix of the eight-bot zoo \\texttt{body} in $S'$, at a shared proof budget $k$ (every "
    "searcher on the row and the column receives the same $k$); a cell gives the row bot's action first. "
    "Cells hold for every sufficiently large $k$ and every sufficient fuel; each white, green or grey cell is a "
    "theorem of $S'$ (\\cref{chapter:lean}). Shaded cells: mutual cooperation (green) and mutual defection "
    "(grey). Orange cells$^{\\ddagger}$ rest on the hinge of \\cref{section:Results-Base}: $S'$ proves a "
    "dichotomy, and the value shown is the engine side (the floor guard not provable within budget); the "
    f"other branch gives {hinge_list}. Highlighted names (yellow) are the bots never exploited within this "
    "zoo on the engine side, i.e.\\ those whose row contains no CD cell: "
    + ", ".join(f"\\texttt{{{b}}}" for b in unexploitable)
    + ("" if unexploitable_h == unexploitable else
       "; on the hinge side the set is " + ", ".join(f"\\texttt{{{b}}}" for b in unexploitable_h))
    + ".}",
    "\\label{table:outcome-matrix}",
    "\\end{table}",
]
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT}  ({len(ORDER)} bots, {len(hinge_pairs)} hinge pairs, unexploitable {unexploitable}, hinge-side {unexploitable_h})")
