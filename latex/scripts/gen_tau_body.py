"""Generate the partial-transparency tables and figures of the paper's base zoo (body8), PA-S'.

Run from `app/`:  uv run python ../latex/scripts/gen_tau_body.py [engine_side|hinge_side]

Outputs in `latex/figures and tables/` (suffix `_hinge_side` for the other floor branch):
  tau_coop_body.tex        (C,C) and (D,D) rates of the tau tournament, behavioral family, α × t
  tau_phase_body.tex       stochastically stable set at (M, β) = (100, 1), behavioral family, α × t
  fig_tau_summary_body     left: mutual-cooperation rate vs t; right: realized cooperation vs t (one curve per α)
  fig_tau_collapse_body    static ceiling (dashed) vs realized cooperation (solid), one panel per α
  fig_tau_families_body    realized cooperation, behavioral (solid) vs syntactic (dashed), one panel per α

Inputs: the tau tournaments (recomputed here from the S' cells through `pd_runner.tau`), and the
sweep analysis `app/generated/egt/analysis[_hinge_side]/{tidy,nash_structure}.csv` (steps 2 and 4,
`python -m pd_runner.egt.analysis` / `python -m pd_runner.egt.nash_structure generated/egt <policy>`).
Realized cooperation = Σ share(i) · [i's self-play is (C,C)] over the Moran stationary distribution at
(100, 1); the static ceiling = the best cooperation rate any extreme Nash equilibrium supports.
Do not edit the outputs by hand.
"""
from __future__ import annotations

import sys
import warnings
from pathlib import Path

import matplotlib
import pandas as pd

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

warnings.simplefilter("ignore")
from pd_runner.tau.channels import all_families  # noqa: E402
from pd_runner.tau.matrix import ZOOS  # noqa: E402
from pd_runner.tau.sweep import run_tournament  # noqa: E402

POLICY = sys.argv[1] if len(sys.argv) > 1 else "engine_side"
ZOO = "body8"
ALPHAS = [0.3, 0.45, 0.62, 0.8, 1.0]
TS = [1.0, 0.8, 0.6, 0.4, 0.2, 0.0]
FAMILIES = ("behavioral", "syntactic")
APP = Path(__file__).resolve().parents[2] / "app"
ANALYSIS = APP / "generated" / "egt" / ("analysis" if POLICY == "engine_side" else f"analysis_{POLICY}")
OUT_DIR = Path(__file__).resolve().parents[1] / "figures and tables"
SUFFIX = "" if POLICY == "engine_side" else f"_{POLICY}"
LABEL_SUFFIX = "" if POLICY == "engine_side" else f"-{POLICY.replace('_', '-')}"
SIDE = "engine side (the floor value)" if POLICY == "engine_side" else "hinge side"
GEN = "% GENERATED by latex/scripts/gen_tau_body.py — do not edit by hand."

# ── tournaments ─────────────────────────────────────────────────────────────
matrix = ZOOS[ZOO].load(source="sprime", floor_policy=POLICY)
families = all_families(matrix)
rates: dict[str, dict[tuple[float, float], tuple[float, float, float]]] = {}
for fam in FAMILIES:
    rates[fam] = {}
    for a in ALPHAS:
        for t in TS:
            r = run_tournament(matrix, t, a, None, family=families[fam])
            n = len(r.cells)
            cc = sum(v == ("C", "C") for v in r.cells.values()) / n
            dd = sum(v == ("D", "D") for v in r.cells.values()) / n
            rates[fam][(a, t)] = (cc, 1 - cc - dd, dd)

# ── sweep analysis ───────────────────────────────────────────────────────────
tidy = pd.read_csv(ANALYSIS / "tidy.csv")
tidy = tidy[(tidy.zoo == ZOO) & (tidy.alpha > 0)]
ns = pd.read_csv(ANALYSIS / "nash_structure.csv")
ns = ns[(ns.zoo == ZOO) & (ns.alpha > 0)]


def grid(df: pd.DataFrame, fam: str, col: str) -> dict[tuple[float, float], object]:
    g = df[df.family == fam]
    return {(float(r.alpha), float(r.t)): getattr(r, col) for r in g.itertuples()}


ss = {fam: grid(tidy, fam, "moran_ss") for fam in FAMILIES}
realized = {fam: grid(ns, fam, "realized_coop") for fam in FAMILIES}
ceiling = {fam: grid(ns, fam, "max_ne_coop") for fam in FAMILIES}
full_ne = {fam: grid(ns, fam, "full_coop_exists") for fam in FAMILIES}
for fam in FAMILIES:
    missing = [(a, t) for a in ALPHAS for t in TS if (a, t) not in realized[fam]]
    assert not missing, f"{fam}: no analysis row at {missing}"


def fa(a: float) -> str:
    return f"{a:.2f}"


def ft(t: float) -> str:
    return "1" if t == 1 else ("0" if t == 0 else f"{t:g}")


def tex_ss(s: str) -> str:
    return "---" if s == "—" else s.replace("+", "+")


# Cell shading on the base matrix's two tones (gen_outcome_matrix_body.py: CC = green, DD = black):
# intensity proportional to the rate, 60 % green / 40 % black at rate 1 so the digits stay legible.
def shade(v: float, tone: str, scale: int) -> str:
    return f"\\cellcolor{{{tone}!{round(scale * v)}}}{v:.2f}"


# ── table: cooperation rates ─────────────────────────────────────────────────
head = " & ".join(f"${ft(t)}$" for t in TS)
lines = [
    f"% figures and tables/tau_coop_body{SUFFIX}.tex — tau-tournament outcome rates, body8, behavioral family, PA-S', hinge cells at the {SIDE}.",
    GEN,
    "% Requires: booktabs, xcolor with colortbl (\\cellcolor).",
    "\\begin{table}[t]\\centering\\small",
    f"\\caption{{Outcome rates of the $\\tau$-tournament on the eight-bot zoo, behavioral family, hinge cells at the {SIDE}: fraction of the 64 ordered pairs that are $(C,C)$ (left) and $(D,D)$ (right); the rest are exploitation pairs. Each row is one caution $\\alpha$, each column one transparency $t$; the $t = 1$ column is the base matrix. Shading is proportional to the rate, green for mutual cooperation and gray for mutual defection.}}",
    f"\\label{{table:tau-coop-body{LABEL_SUFFIX}}}",
    "\\begin{tabular}{@{}l" + "c" * len(TS) + "@{\\hspace{1.5em}}" + "c" * len(TS) + "@{}}\\toprule",
    f"& \\multicolumn{{{len(TS)}}}{{c}}{{$(C,C)$ rate}} & \\multicolumn{{{len(TS)}}}{{c}}{{$(D,D)$ rate}} \\\\",
    f"\\cmidrule(lr){{2-{1 + len(TS)}}}\\cmidrule(lr){{{2 + len(TS)}-{1 + 2 * len(TS)}}}",
    f"$\\alpha \\backslash t$ & {head} & {head} \\\\\\midrule",
]
for a in ALPHAS:
    cc = " & ".join(shade(rates["behavioral"][(a, t)][0], "green", 60) for t in TS)
    dd = " & ".join(shade(rates["behavioral"][(a, t)][2], "black", 40) for t in TS)
    lines.append(f"{fa(a)} & {cc} & {dd} \\\\")
lines[-1] = lines[-1][:-2] + "\\\\\\bottomrule"
lines += ["\\end{tabular}", "\\end{table}"]
(OUT_DIR / f"tau_coop_body{SUFFIX}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

# ── table: phase (stochastically stable set) ─────────────────────────────────
lines = [
    f"% figures and tables/tau_phase_body{SUFFIX}.tex — stochastically stable set at (M, β) = (100, 1), body8, behavioral family, PA-S', hinge cells at the {SIDE}.",
    GEN,
    "\\begin{table}[t]\\centering\\small",
    f"\\caption{{Stochastically stable set at $(M,\\beta)=(100,1)$ on the eight-bot zoo, behavioral family, hinge cells at the {SIDE}. Adjacent equal cells form one phase region; \\enquote{{---}} means no type reaches the stability threshold.}}",
    f"\\label{{table:tau-phase-body{LABEL_SUFFIX}}}",
    "\\begin{tabular}{@{}l" + "c" * len(TS) + "@{}}\\toprule",
    "$\\alpha$ & " + " & ".join(f"$t = {ft(t)}$" if t == 1 else f"${ft(t)}$" for t in TS) + " \\\\\\midrule",
]
for a in ALPHAS:
    lines.append(f"{fa(a)} & " + " & ".join(tex_ss(ss["behavioral"][(a, t)]) for t in TS) + " \\\\")
lines[-1] = lines[-1][:-2] + "\\\\\\bottomrule"
lines += ["\\end{tabular}", "\\end{table}"]
(OUT_DIR / f"tau_phase_body{SUFFIX}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

# ── figures ──────────────────────────────────────────────────────────────────
plt.rcParams.update({"font.size": 9, "axes.titlesize": 9, "legend.fontsize": 8,
                     "axes.spines.top": False, "axes.spines.right": False})
colors = {a: plt.get_cmap("viridis")(i / (len(ALPHAS) - 1)) for i, a in enumerate(ALPHAS)}


def save(fig, name: str) -> None:
    fig.savefig(OUT_DIR / f"{name}.pdf", bbox_inches="tight")
    fig.savefig(OUT_DIR / f"{name}.preview.png", dpi=150, bbox_inches="tight")
    plt.close(fig)


# summary: mutual cooperation rate and realized cooperation vs t, one curve per α
fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.6), sharex=True)
for a in ALPHAS:
    axes[0].plot(TS, [rates["behavioral"][(a, t)][0] for t in TS], "o-", ms=3, color=colors[a], label=f"$\\alpha={a:g}$")
    axes[1].plot(TS, [realized["behavioral"][(a, t)] for t in TS], "o-", ms=3, color=colors[a], label=f"$\\alpha={a:g}$")
axes[0].set_title("$(C,C)$ rate of the $\\tau$-tournament")
axes[1].set_title("realized cooperation, $(M,\\beta)=(100,1)$")
for ax in axes:
    ax.set_xlabel("transparency $t$")
    ax.set_xlim(1.02, -0.02)
    ax.set_ylim(-0.03, 1.03)
    ax.grid(alpha=0.25)
axes[1].legend(loc="lower left", ncol=1, frameon=False)
save(fig, f"fig_tau_summary_body{SUFFIX}")

# collapse: static ceiling vs realized cooperation, one panel per α
fig, axes = plt.subplots(1, len(ALPHAS), figsize=(7.0, 1.9), sharex=True, sharey=True)
for ax, a in zip(axes, ALPHAS):
    ax.plot(TS, [ceiling["behavioral"][(a, t)] for t in TS], "--", color="0.35", label="static ceiling")
    ax.plot(TS, [realized["behavioral"][(a, t)] for t in TS], "o-", ms=3, color=colors[a], label="realized")
    ax.set_title(f"$\\alpha = {a:g}$")
    ax.set_xlim(1.02, -0.02)
    ax.set_ylim(-0.03, 1.03)
    ax.grid(alpha=0.25)
    ax.set_xlabel("$t$")
axes[0].legend(loc="lower left", frameon=False)
save(fig, f"fig_tau_collapse_body{SUFFIX}")

# families: realized cooperation, behavioral vs syntactic, one panel per α
fig, axes = plt.subplots(1, len(ALPHAS), figsize=(7.0, 1.9), sharex=True, sharey=True)
for ax, a in zip(axes, ALPHAS):
    ax.plot(TS, [realized["behavioral"][(a, t)] for t in TS], "o-", ms=3, color=colors[a], label="behavioral")
    ax.plot(TS, [realized["syntactic"][(a, t)] for t in TS], "s--", ms=3, color=colors[a], alpha=0.7, label="syntactic")
    ax.set_title(f"$\\alpha = {a:g}$")
    ax.set_xlim(1.02, -0.02)
    ax.set_ylim(-0.03, 1.03)
    ax.grid(alpha=0.25)
    ax.set_xlabel("$t$")
axes[0].legend(loc="lower left", frameon=False)
save(fig, f"fig_tau_families_body{SUFFIX}")

# ── headline numbers for the prose ───────────────────────────────────────────
print(f"[{POLICY}] body8, families {FAMILIES}; outputs with suffix {SUFFIX!r} in {OUT_DIR}")
for fam in FAMILIES:
    print(f"--- {fam}")
    for a in ALPHAS:
        cc = [rates[fam][(a, t)][0] for t in TS]
        dd = [rates[fam][(a, t)][2] for t in TS]
        rc = [realized[fam][(a, t)] for t in TS]
        ce = [ceiling[fam][(a, t)] for t in TS]
        # critical transparency: the lowest grid t at which realized cooperation is still >= 1/2
        alive = [t for t in TS if realized[fam][(a, t)] >= 0.5]
        t_c = min(alive) if alive else None
        gone = [t for t in TS if not full_ne[fam][(a, t)]]
        t_static = max(gone) if gone else None
        print(f"α={a:4.2f}  CC {' '.join(f'{x:.2f}' for x in cc)} | DD {' '.join(f'{x:.2f}' for x in dd)} | "
              f"realized {' '.join(f'{x:.2f}' for x in rc)} | ceiling {' '.join(f'{x:.2f}' for x in ce)} | "
              f"t_c={t_c} t_static(first t without a full-coop NE)={t_static} | SS {' '.join(ss[fam][(a, t)] for t in TS)}")
diff_ss = sum(ss["behavioral"][(a, t)] != ss["syntactic"][(a, t)] for a in ALPHAS for t in TS)
diff_rc = sum(abs(realized["behavioral"][(a, t)] - realized["syntactic"][(a, t)]) > 0.05 for a in ALPHAS for t in TS)
print(f"families disagree on the stable set at {diff_ss}/{len(ALPHAS) * len(TS)} points (α>0); "
      f"realized cooperation differs by >0.05 at {diff_rc} points")
