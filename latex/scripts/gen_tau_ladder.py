"""Generate the transparency ladder and the aggregator table of the partial-transparency section, PA-S',
engine side (the floor value).

Run from `app/`:  uv run python ../latex/scripts/gen_tau_ladder.py

Outputs in `latex/figures and tables/`:
  tau_ladder.tex       per zoo rung (7, 8, 10, 12 bots) and caution α: the critical transparency t_c(α), the
                       lowest grid transparency at which the realized cooperation of the Moran stationary
                       distribution at (M, β) = (100, 1) is still at least 1/2; behavioral family
  tau_aggregators.tex  body8 + MaxConfidenceBot + MinConfidenceBot, behavioral family: stationary shares at
                       (100, 1) of the three aggregators over DupocBot's test (sum = DupocBot, max, min) and
                       the stochastically stable set, over the (α, t) grid

Inputs: the run directories `app/generated/egt/runs/<zoo>_sprime[_<family>]_t<NNN>_a<NNN>_<fp>/`
(`summary.json` for the grid points a matrix covers, `moran/stationary.json`, `ess/payoff_matrix_numeric.csv`).
Realized cooperation = Σ share(i) · [i's self-play is (C,C)], read off the payoff diagonal. Do not edit the
outputs by hand.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

APP = Path(__file__).resolve().parents[2] / "app"
RUNS = APP / "generated" / "egt" / "runs"
OUT_DIR = Path(__file__).resolve().parents[1] / "figures and tables"
GEN = "% GENERATED by latex/scripts/gen_tau_ladder.py — do not edit by hand."
ALPHAS = [0.3, 0.45, 0.62, 0.8]
TS = [1.0, 0.8, 0.6, 0.4, 0.2, 0.0]
LADDER = [
    ("nonprovers+dupoc", 7, "non-provers + \\texttt{DupocBot}"),
    ("body8", 8, "\\texttt{body}"),
    ("body8+trolls", 10, "+ trolls"),
    ("body8+trolls+provers", 12, "+ trolls + \\texttt{CIMCIC} + \\texttt{DIMDID}"),
]
ABBREV = {"CooperateBot": "Coop", "DefectBot": "Def", "TitForTatBot": "TFT", "DupocBot": "Dup",
          "CupodBot": "Cup", "CupodTrollBot": "CupT", "DupocTrollBot": "DupT", "DBot": "DB", "EBot": "EB",
          "OBot": "OB", "CIMCIC": "CIM", "DIMDID": "DID", "MaxConfidenceBot": "Max", "MinConfidenceBot": "Min"}


def short(bots: list[str]) -> str:
    return "+".join(ABBREV.get(b, b) for b in sorted(bots)) if bots else "---"


def load_points(zoo: str, family: str = "behavioral", floor_policy: str = "engine_side") -> dict:
    """(α, t) -> {'shares', 'ss', 'realized', 'n'} at (M, β) = (100, 1), from every complete run of the sweep."""
    out: dict[tuple[float, float], dict] = {}
    for s in sorted(RUNS.glob("*/summary.json")):
        j = json.load(open(s))
        if (j["zoo"], j.get("family", "behavioral"), j.get("floor_policy", "engine_side")) != (zoo, family, floor_policy):
            continue
        if not j["ok"]:
            raise SystemExit(f"{j['run']}: failed stages {j['failed_stages']}")
        d = s.parent
        mo = json.load(open(d / "moran" / "stationary.json"))
        (pt,) = [p for p in mo["points"] if p["population"] == 100 and p["beta"] == 1.0]
        rows = list(csv.reader(open(d / "ess" / "payoff_matrix_numeric.csv")))
        hdr = rows[0][1:]
        diag = {r[0]: float(r[1 + hdr.index(r[0])]) > 0 for r in rows[1:]}
        shares = dict(pt["stationary"])
        rec = {"shares": shares, "ss": short(pt["stochastically_stable"]),
               "realized": sum(v * diag[b] for b, v in shares.items()), "n": len(mo["names"])}
        for t, a in j["grid_points"]:
            out[(float(a), float(t))] = rec
    return out


def ft(t: float) -> str:
    return "1" if t == 1 else ("0" if t == 0 else f"{t:g}")


# ── the transparency ladder ──────────────────────────────────────────────────
lines = [
    "% figures and tables/tau_ladder.tex — the transparency ladder: critical transparency per zoo rung and caution, PA-S', engine side, behavioral family.",
    GEN,
    "\\begin{table}[t]\\centering\\small",
    "\\caption{Critical transparency $t_c(\\alpha)$ on the four nested zoos, behavioral family, hinge cells at the engine side: the lowest transparency on the grid $t \\in \\{0, 0.2, \\dots, 1\\}$ at which the realized cooperation of the evolved population at $(M,\\beta)=(100,1)$ is still at least $\\tfrac12$ (\\enquote{---}: below $\\tfrac12$ already at $t = 1$). The second column is the realized cooperation at full transparency.}",
    "\\label{tab:tau-ladder}",
    "\\begin{tabular}{@{}lrc" + "c" * len(ALPHAS) + "@{}}\\toprule",
    "zoo & $N$ & coop.\\ at $t{=}1$ & " + " & ".join(f"$\\alpha = {a:g}$" for a in ALPHAS) + " \\\\\\midrule",
]
summary = {}
for key, n, label in LADDER:
    pts = load_points(key)
    missing = [(a, t) for a in ALPHAS for t in TS if (a, t) not in pts]
    if missing:
        raise SystemExit(f"{key}: no run at {missing}")
    cells = []
    for a in ALPHAS:
        alive = [t for t in TS if pts[(a, t)]["realized"] >= 0.5]
        tc = min(alive) if alive else None
        cells.append("---" if tc is None else f"${ft(tc)}$")
        summary[(key, a)] = (tc, [round(pts[(a, t)]["realized"], 2) for t in TS], [pts[(a, t)]["ss"] for t in TS])
    r1 = pts[(ALPHAS[0], 1.0)]["realized"]
    lines.append(f"{label} & {n} & {r1:.2f} & " + " & ".join(cells) + " \\\\")
lines[-1] = lines[-1][:-2] + "\\\\\\bottomrule"
lines += ["\\end{tabular}", "\\end{table}"]
(OUT_DIR / "tau_ladder.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

print("ladder: zoo, α -> t_c | realized along t=1..0 | stable set along t")
for (key, a), (tc, rc, ss) in summary.items():
    print(f"  {key:22s} α={a:<5g} t_c={tc}  realized {rc}  SS {ss}")

# ── the aggregator tables: one per signal family that has a body8+natives sweep ──
# The ε-uniform family is the comparison's primary channel (identity-based: no twin ceiling — the
# natives are Dupoc twins as hypotheses, so a distance-based channel spreads Dupoc's mass over three
# names and confounds the aggregator with the twinning); the distance families are the robustness check.
FAMILY_LABEL = {"epsilon": "$\\varepsilon$-uniform family", "behavioral": "behavioral family",
                "syntactic": "syntactic family"}
for family in ("epsilon", "behavioral", "syntactic"):
    pts = load_points("body8+natives", family)
    missing = [(a, t) for a in ALPHAS for t in TS if (a, t) not in pts]
    if missing:
        print(f"body8+natives/{family}: no run at {missing} — aggregator table NOT written")
        continue
    AGG = [("DupocBot", "sum"), ("MaxConfidenceBot", "max"), ("MinConfidenceBot", "min")]
    fname = "tau_aggregators.tex" if family == "epsilon" else f"tau_aggregators_{family}.tex"
    label = "table:tau-aggregators" if family == "epsilon" else f"table:tau-aggregators-{family}"
    lines = [
        f"% figures and tables/{fname} — the three aggregators over DupocBot's test on body8 + natives, PA-S', engine side, {family} family.",
        GEN,
        "\\begin{table}[t]\\centering\\small",
        f"\\caption{{Stationary shares at $(M,\\beta)=(100,1)$ on the eight-bot zoo plus the two native aggregators, {FAMILY_LABEL[family]}, hinge cells at the engine side. The three aggregators over \\texttt{{DupocBot}}'s test: \\enquote{{sum}} is the lift \\texttt{{DupocBot}} itself, \\enquote{{max}} is \\texttt{{MaxConfidenceBot}}, \\enquote{{min}} is \\texttt{{MinConfidenceBot}}; \\enquote{{Löbian}} is their combined share. As hypotheses the three are twins, so at $t = 1$ they are payoff-identical and the share splits evenly; they separate only once the signal blurs. The last column is the stochastically stable set.}}",
        f"\\label{{{label}}}",
        "\\begin{tabular}{@{}llrrrrl@{}}\\toprule",
        "$\\alpha$ & $t$ & sum & max & min & Löbian & stable set \\\\\\midrule",
    ]
    print(f"aggregators (body8+natives, {family}): α t | sum max min | Löbian | SS | realized")
    for i, a in enumerate(ALPHAS):
        for t in TS:
            sh = pts[(a, t)]["shares"]
            vals = [sh.get(b, 0.0) for b, _ in AGG]
            lines.append(f"{a:.2f} & {ft(t)} & " + " & ".join(f"{100 * v:.0f}\\%" for v in vals)
                         + f" & {100 * sum(vals):.0f}\\% & {pts[(a, t)]['ss']} \\\\")
            print(f"  {a:<5g} {t:<4g} | " + " ".join(f"{100 * v:5.1f}" for v in vals)
                  + f" | {100 * sum(vals):5.1f} | {pts[(a, t)]['ss']:14s} | {pts[(a, t)]['realized']:.2f}")
        if i + 1 < len(ALPHAS):
            lines[-1] = lines[-1] + "\\midrule"
    lines[-1] = lines[-1][:-2] + "\\\\\\bottomrule"
    lines += ["\\end{tabular}", "\\end{table}"]
    (OUT_DIR / fname).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {fname}")
print("wrote tau_ladder.tex")
